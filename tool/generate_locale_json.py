def t_step(en: str, lang: str) -> str:
    if en in STEPS:
        return STEPS[en][0 if lang == "hi" else 1]
    return en


def t_pose(name: str, lang: str) -> str:
    if name in POSE:
        return POSE[name][0 if lang == "hi" else 1]
    return name


def translate_chakra(c: dict, lang: str) -> dict:
    meta = CHAKRA.get(c["name"], {}).get(lang, {})
    color_t = COLOR.get(c["color"], (c["color"], c["color"]))
    elem_t = ELEMENT.get(c["element"], (c["element"], c["element"]))
    idx = 0 if lang == "hi" else 1

    yogasana = {}
    for pose_name, pose in c["yogasana"].items():
        yogasana[t_pose(pose_name, lang)] = {
            "image": pose["image"],
            "steps": [t_step(s, lang) for s in pose["steps"]],
        }

    return {
        "name": meta.get("name", c["name"]),
        # Keep English color keys so chakraColor() mapping stays stable.
        "color": c["color"],
        "element": elem_t[idx],
        "location": meta.get("location", c["location"]),
        "function": meta.get("function", c["function"]),
        "mantra": c["mantra"],
        "image": c["image"],
        "music": c["music"],
        "yogasana": yogasana,
    }


def main():
    data = json.loads(EN.read_text(encoding="utf-8"))
    for lang, path in (("hi", ROOT / "chakras_hi.json"), ("ja", ROOT / "chakras_ja.json")):
        out = [translate_chakra(c, lang) for c in data]
        path.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
